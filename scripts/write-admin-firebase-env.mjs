#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const projectId = process.env.URAI_ADMIN_FIREBASE_PROJECT || 'urai-4dc1d';
const webAppId = process.env.URAI_ADMIN_WEB_APP_ID || '1:952723774155:web:d91a008eaded03fd25994e';
const outputPath = process.env.URAI_ADMIN_ENV_OUTPUT || 'apps/urai-admin/.env.local';

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function readSdkConfig() {
  try {
    const output = execFileSync(
      'firebase',
      ['apps:sdkconfig', 'WEB', webAppId, '--project', projectId, '--json'],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
    );
    const parsed = JSON.parse(output);
    return parsed.result?.sdkConfig || parsed.result || parsed;
  } catch (error) {
    const stderr = error?.stderr ? String(error.stderr) : '';
    fail(`Unable to read Firebase Web SDK config for ${webAppId} in ${projectId}. ${stderr}`);
  }
}

const config = readSdkConfig();
const required = ['apiKey', 'authDomain', 'projectId', 'storageBucket', 'messagingSenderId', 'appId'];
const missing = required.filter((key) => !config[key]);

if (missing.length) {
  fail(`Firebase SDK config is missing required keys: ${missing.join(', ')}`);
}

if (config.projectId !== projectId) {
  fail(`Firebase SDK config projectId ${config.projectId} does not match expected ${projectId}`);
}

const env = [
  '# Generated by scripts/write-admin-firebase-env.mjs',
  '# Do not commit this file. Re-run pnpm env:admin:firebase when Firebase Web App config changes.',
  `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${config.projectId}`,
  `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${config.authDomain}`,
  `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${config.storageBucket}`,
  `NEXT_PUBLIC_FIREBASE_API_KEY=${config.apiKey}`,
  `NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${config.messagingSenderId}`,
  `NEXT_PUBLIC_FIREBASE_APP_ID=${config.appId}`,
  config.measurementId ? `NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID=${config.measurementId}` : '',
].filter(Boolean).join('\n') + '\n';

const absoluteOutput = resolve(outputPath);
const parent = dirname(absoluteOutput);
if (!existsSync(parent)) mkdirSync(parent, { recursive: true });
writeFileSync(absoluteOutput, env, 'utf8');

console.log(`OK: wrote ${outputPath} for Firebase project ${projectId}`);
console.log(`OK: Web App ID ${webAppId}`);
